package JavaOperators;

public class RelationalOperator {

	public static void main(String[] args) {
		int x=8;
		int y=10;
		boolean result= x==y;
		
		System.out.println("x==y " +result);
		result=x!=y;
		
		System.out.println("x!=y " +result);
		result=x>y;
		
		System.out.println("x>y " +result);
		result=x>=y;
		
		System.out.println("x>=y " +result);
		result=x<y;
		
		
		

	}

}
