package DecisionMakingStatements;

public class SwitchCase {

	public static void main(String[] args) {
		int num=4;
		
		switch(num) {
		
		case 0:
			System.out.println("Num 0:HYD");
			break;
			
		case 1:
			System.out.println("Num 1:CCU");
			break;
			
		case 2:
			System.out.println("Num 2:XRS");
			break;
			
		case 3:
			System.out.println("Num 3:BLR");
			break;
			
		default:
			System.out.println("Number is not present");
		}

	}

}
